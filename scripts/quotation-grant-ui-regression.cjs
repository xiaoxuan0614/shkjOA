const fs = require('node:fs');
const assert = require('node:assert/strict');
const { parse, compileScript, compileTemplate } = require('@vue/compiler-sfc');
const filename = 'src/views/plan/material-draft/QuotationGrantModal.vue';
const source = fs.readFileSync(filename, 'utf8');
const { descriptor } = parse(source);
compileScript(descriptor, { id: 'grant' });
assert.deepEqual(compileTemplate({ source: descriptor.template.content, filename, id: 'grant' }).errors, []);
assert.match(source, /v-model:checked="canEditPrice"/);
assert.match(source, /v-model:checked="canExport"/);
assert.match(source, /canViewPrice: canEditPrice, canEditPrice, canExport/);
assert.match(source, /updateGrant\(target, version.value, canEditPrice.value, canExport.value\)/);
assert.match(source, /updateGrant\(String\(row.userId\), quotationVersion\(row.version\), false, false\)/);
assert.match(source, /canEditPrice.value = Number\(item\?\.canEditPrice\) === 1/);
assert.match(source, /current.version\) : 0\) !== payload.version/);
assert.match(source, /操作已成功，但列表刷新失败/);
const contract = fs.readFileSync('src/views/project/contract/index.vue', 'utf8');
assert.match(contract, /v-if="quotationAccess.canRevise"/);
assert.match(contract, /quotationAccess.value.canRevise &&/);
console.log('Grant modal compilation, edit/export payload, revoke, version and revise visibility guards passed');
