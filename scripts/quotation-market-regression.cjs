const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const ts = require('typescript');
function load(file) {
  const exports = {};
  vm.runInNewContext(ts.transpileModule(fs.readFileSync(file, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText, { exports, require });
  return exports;
}
const { previewQuotationRoute } = load('src/views/plan/quotationRoute.ts');
const departments = [{ id: 'm', departName: '市场部', status: null }, { id: 't', departName: '技术部', status: 1 }];
assert.equal(previewQuotationRoute(['m'], departments), 'MARKET');
assert.equal(previewQuotationRoute(['m', 't'], departments), 'TECHNICAL');
assert.equal(previewQuotationRoute(['x'], departments), '');
assert.equal(previewQuotationRoute(['m'], [...departments, { id: 'm2', departName: '市场部' }]), '');
assert.equal(previewQuotationRoute(['m'], [{ id: 'm', departName: '市场部', status: 0 }]), '');
const g = load('src/views/plan/quotationGovernance.ts');
const market = { id: 'a', approvalRoute: 'MARKET', status: '2', version: 1 };
const rejected = { ...market, status: '0', createBy: 'wang' };
assert.equal(g.quotationListCapabilities(rejected, () => true, { username: 'wang' }).submit, true);
assert.equal(g.quotationListCapabilities(rejected, () => true, { username: 'wang' }).edit, true);
const button = code => code === 'plan:quotation:lock';
assert.equal(g.quotationListCapabilities(market, button).approve, true);
assert.equal(g.quotationCapabilities(market, { canApprove: true }, {}, button).approve, true);
assert.equal(g.quotationCapabilities(market, { canManage: true, canApprove: false }, {}, button).approve, false);
assert.equal(g.quotationListCapabilities({ ...market, status: '1' }, () => true).price, false);
const editor = fs.readFileSync('src/views/plan/material-draft/editor.vue', 'utf8');
const table = fs.readFileSync('src/views/plan/components/MaterialPlanTable.vue', 'utf8');
assert(editor.includes(':pricing-editable="directEntry ? canModify : canEditPricing"'));
assert(editor.includes("creationRoute.value === 'MARKET'"));
assert(editor.includes("'basePrice', 'finalPrice', 'remark'"));
assert(editor.includes('getQuotationAccess(periodId, candidateId.value)'));
assert(table.includes("props.directQuotation ? '报价' : '指导价'"));
assert(table.includes('props.pricingEditable && !props.directQuotation'));
assert(table.includes("...(!props.directQuotation ? { markupRate: item.markupRate } : {}), finalPrice: item.finalPrice"));
assert(table.includes("field: 'finalPrice', label: '报价', required: true"));
assert(table.includes('basePrice: props.directQuotation ? 0 : material.costPrice ?? 0'));
assert(table.includes("props.mode === 'quotation' && props.directQuotation ? { finalPrice: '0.00' } : {}"));
console.log('Market route, approval boundary, price column, payload and draft checks passed');
