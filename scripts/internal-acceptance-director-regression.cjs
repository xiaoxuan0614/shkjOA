const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
const source = fs.readFileSync('src/views/project/internalAcceptanceAccess.ts', 'utf8');
const js = ts.transpile(source, { module: ts.ModuleKind.CommonJS });
let calls = 0;
let response = { success: true, result: [{ id: 'ops', departName: '运维部', status: '0' }] };
const exportsObject = {};
new Function('require', 'exports', js)(() => ({ defHttp: { get: async () => { calls++; return response; } } }), exportsObject);
const { isOperationsDirector, readInternalAcceptanceAccess } = exportsObject;
const identity = { userId: 'user', roleCodes: [], responsibleDepartmentIds: ['ops'] };
(async () => {
  assert.equal(await readInternalAcceptanceAccess(identity), true);
  assert.equal(await readInternalAcceptanceAccess({ ...identity, responsibleDepartmentIds: ['other'], roleCodes: ['operations_manager'] }), false);
  const before = calls;
  assert.equal(await readInternalAcceptanceAccess({ ...identity, responsibleDepartmentIds: [] }), false);
  assert.equal(await readInternalAcceptanceAccess({ ...identity, responsibleDepartmentIds: [], roleCodes: ['admin'] }), true);
  assert.equal(calls, before);
  assert.equal(await readInternalAcceptanceAccess({ ...identity, userId: '' }), false);
  assert.equal(isOperationsDirector(['ops'], [{ children: response.result }]), true);
  assert.equal(isOperationsDirector(['ops-prefix'], response.result), false);
  assert.equal(isOperationsDirector(['ops'], [...response.result, { id: 'other', title: '运维部' }]), false);
  assert.equal(isOperationsDirector(['ops'], [{ id: 'ops', title: '运维部', delFlag: '1' }]), false);
  response = { success: false };
  await assert.rejects(readInternalAcceptanceAccess(identity));
  const { parse, compileScript, compileTemplate } = require('@vue/compiler-sfc');
  const filename = 'src/views/project/detail/components/DetailAcceptance.vue';
  const { descriptor } = parse(fs.readFileSync(filename, 'utf8'));
  compileScript(descriptor, { id: 'acceptance' });
  assert.deepEqual(compileTemplate({ source: descriptor.template.content, filename, id: 'acceptance' }).errors, []);
  console.log('Internal acceptance director access and SFC checks passed');
})().catch(error => { console.error(error); process.exitCode = 1; });
