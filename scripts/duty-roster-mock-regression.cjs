const fs = require('node:fs');
const assert = require('node:assert/strict');
const ts = require('typescript');
const dayjs = require('dayjs');
const storage = new Map();
global.localStorage = { getItem: key => storage.get(key) ?? null, setItem: (key, value) => storage.set(key, value) };
let actor = '测试创建人';
function load(file) {
  const output = {};
  const source = fs.readFileSync(`src/views/operation/duty-roster/${file}.ts`, 'utf8');
  const js = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022, esModuleInterop: true } }).outputText;
  new Function('require', 'exports', js)(name => name.includes('store/modules/user') ? { useUserStore: () => ({ getUserInfo: { realname: actor } }) } : name === './dutyRoster.rules' ? load('dutyRoster.rules') : require(name), output);
  return output;
}
(async () => {
  const mock = load('dutyRoster.mock');
  const seeded = await mock.listDutyRosters();
  assert.equal(seeded.length, 3);
  assert.equal((await mock.listDutyRosters(seeded[0].month.slice(0, 4), seeded[0].month.slice(5))).length, 1);
  assert.equal((await mock.listDutyRosters('1990')).length, 0);
  const people = (await mock.loadDutyRosterUsers()).persons;
  const { getRestUsers } = load('dutyRoster.rules');
  const single = { dayUsers: [people[0]], nightUser: people[0] };
  assert.deepEqual(getRestUsers(people, single).map(p => p.userId), people.slice(1).map(p => p.userId));
  assert.equal(getRestUsers(people, { dayUsers: people, nightUser: people[0] }).length, 0);
  assert.equal(getRestUsers([...people, people[1], null], { dayUsers: [], nightUser: null }).length, 3);
  assert.equal(getRestUsers(people.slice(0, 2), single).length, 1);
  const payload = { month: '2030-01', version: 0, rotationUsers: people, days: [{ date: '2030-01-01', dayUsers: [people[0]], nightUser: people[2], restUser: null }] };
  await mock.saveDutyRoster(payload);
  actor = '测试更新人';
  await mock.saveDutyRoster({ ...payload, version: 1 });
  const row = (await mock.listDutyRosters('2030', '01'))[0];
  assert.equal(row.createdBy, '测试创建人'); assert.equal(row.updatedBy, actor);
  assert.equal(row.days[0].dayUsers.length, 1);
  assert.equal(row.version, 2); assert.ok(dayjs(row.updatedAt).isValid());
  await assert.rejects(mock.saveDutyRoster(payload), /已更新/);
  assert.equal((await load('dutyRoster.mock').queryDutyRoster('2030-01')).version, 2);
  const blob = await mock.downloadDutyRoster('2030-01');
  const book = new (require('exceljs').Workbook)(); await book.xlsx.load(await blob.arrayBuffer());
  assert.equal(book.worksheets[0].getCell('B2').value, people[0].name);
  assert.equal(book.worksheets[0].getCell('D2').value, people[2].phone);
  assert.equal(book.worksheets[0].getCell('E2').value, people[1].name);
  await mock.saveDutyRoster({ ...payload, version: 2, days: [{ ...payload.days[0], nightUser: people[0] }] });
  const updated = await mock.queryDutyRoster('2030-01');
  assert.equal(updated.days[0].restUsers.length, 2);
  await book.xlsx.load(await (await mock.downloadDutyRoster('2030-01')).arrayBuffer());
  assert.equal(book.worksheets[0].getCell('E2').value, people.slice(1).map(p => p.name).join('、'));
  await mock.saveDutyRoster({ ...payload, version: 3, days: [{ ...payload.days[0], nightUsers: [people[0], people[1]] }] });
  const multi = await mock.queryDutyRoster('2030-01');
  assert.equal(multi.days[0].nightUsers.length, 2);
  assert.deepEqual(multi.days[0].restUsers.map(p => p.userId), [people[2].userId]);
  await book.xlsx.load(await (await mock.downloadDutyRoster('2030-01')).arrayBuffer());
  assert.equal(book.worksheets[0].getCell('C2').value, people.slice(0, 2).map(p => p.name).join('、'));
  assert.equal(book.worksheets[0].getCell('D2').value, people.slice(0, 2).map(p => p.phone).join('、'));
  console.log('PASS Mock 月份筛选、同月去重、创建更新人、人工修改、持久化和 Excel 内容');
})().catch(e => { console.error(e); process.exit(1); });
