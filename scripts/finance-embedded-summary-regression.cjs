const fs = require('node:fs');
const assert = require('node:assert/strict');
const { parse, compileScript, compileTemplate } = require('@vue/compiler-sfc');
const file = 'src/views/payment/FinanceDetail.vue';
const source = fs.readFileSync(file, 'utf8');
const block = source.match(/<a-descriptions v-if="embedded"[\s\S]*?<\/a-descriptions>/)[0];
assert.deepEqual([...block.matchAll(/label="([^"]+)"/g)].map(m => m[1]), ['合同金额', '回款状态', '已回款金额', '剩余回款金额', '开票状态']);
assert.match(source, /v-if="!embedded && allowed && summary"/);
assert.match(source, /<a-drawer v-if="!embedded"/);
assert.match(source, /financePeriods\(\{ periodId, pageNo: 1, pageSize: 1 \}\)/);
assert.match(source, /String\(item.periodId\) === periodId/);
assert.match(source, /financialOverview.value = overview/);
assert.match(source, /loadDictOptions\('payment_status'\)/);
assert.match(source, /loadDictOptions\('invoice_status'\)/);
assert.match(block, /financialOverview\?\.projectAmount/);
const { descriptor } = parse(source);
const script = compileScript(descriptor, { id: file });
assert.deepEqual(compileTemplate({ source: descriptor.template.content, filename: file, id: file, compilerOptions: { bindingMetadata: script.bindings } }).errors, []);
console.log('PASS embedded finance five-field summary, hidden contract action, scoped lookup, dictionaries and SFC');
