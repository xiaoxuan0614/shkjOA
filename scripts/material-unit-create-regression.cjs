const fs = require('node:fs');
const assert = require('node:assert/strict');
const ts = require('typescript');
const { parse, compileScript, compileTemplate } = require('@vue/compiler-sfc');
const read = file => fs.readFileSync(file, 'utf8');
const goods = read('src/views/material/goods/components/GoodsModal.vue');
for (const file of ['src/views/material/goods/components/GoodsModal.vue', 'src/views/material/goods/components/BrandManageModal.vue', 'src/components/EditableTable/UniqueRowSelect.vue']) {
  const { descriptor, errors } = parse(read(file), { filename: file });
  assert.deepEqual(errors, []);
  const script = compileScript(descriptor, { id: file });
  assert.deepEqual(compileTemplate({ source: descriptor.template.content, filename: file, id: file, compilerOptions: { bindingMetadata: script.bindings } }).errors, []);
}
assert.match(goods, /dict-code="inv_unit" item-label="单位"/);
assert.match(goods, /@click="openUnitCreate\(record\)"/);
assert.match(goods, /unitCreateUid.value = undefined/);
const source = goods.match(/function selectCreatedUnit\([^]*?\n  \}/)[0];
const row = { uid: 1, unitName: '个' };
const other = { uid: 2, unitName: '箱' };
const unitList = { value: [row, other] }, target = { value: 1 }, readOnly = { value: false }, warnings = [];
const select = new Function('unitList', 'unitCreateUid', 'readOnly', 'createMessage', ts.transpile(source) + '; return selectCreatedUnit;')(unitList, target, readOnly, { warning: msg => warnings.push(msg) });
select('code-3', { itemText: '套' });
assert.equal(row.unitName, '套', 'must store name, not dictionary code');
assert.equal(target.value, undefined);
target.value = 1;
select('code-2', { itemText: '箱' });
assert.equal(row.unitName, '套');
assert.equal(warnings.length, 1);
target.value = 999;
select('code-4', { itemText: '米' });
assert.equal(row.unitName, '套', 'removed or reopened row must not be changed');
target.value = 1; readOnly.value = true;
select('code-4', { itemText: '米' });
assert.equal(row.unitName, '套');
const updateSource = read('src/views/material/material.util.ts').match(/export function updateUnitDictionary\([^]*?\n\}/)[0].replace('export ', '');
const update = new Function(ts.transpile('const dictCache = {}; let unitOptionsCache = null;\n' + updateSource) + '; return rows => ({ options: updateUnitDictionary(rows), dict: dictCache.inv_unit });')();
const updated = update([{ status: 1, itemText: '套', itemValue: 'code-3' }, { status: 0, itemText: '停用', itemValue: 'off' }]);
assert.deepEqual(updated.options, [{ label: '套', value: '套' }]);
assert.equal(updated.dict['code-3'].text, '套');
assert.equal(updated.dict.off, undefined);
console.log('PASS unit create: shared dictionary modal, name storage, duplicate/read-only/stale-row guards, cache refresh and SFC');
