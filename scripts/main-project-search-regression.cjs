const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const ts = require('typescript');
const vue = require('@vue/compiler-sfc');
let timer;
const context = { exports: {}, Error, require: () => ({ ref: (value) => ({ value }) }), setTimeout: (fn) => { timer = fn; return 1; }, clearTimeout: () => { timer = undefined; } };
vm.runInNewContext(ts.transpileModule(fs.readFileSync('src/views/project/mainProjectSearch.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText, context);
const calls = [];
const pending = [];
let selected;
const search = context.exports.useMainProjectSearch((params) => {
  calls.push(params);
  return new Promise((resolve, reject) => pending.push({ resolve, reject }));
}, () => selected);
const tick = () => new Promise(setImmediate);
(async () => {
  search.reset(); assert.equal(calls.length, 0);
  search.open(true); assert.equal(calls.length, 1);
  assert.deepEqual(JSON.parse(JSON.stringify(calls[0])), { pageNo: 1, pageSize: 20 });
  pending.shift().resolve({ records: [{ projectId: 'p1', projectName: '主项目', periodId: 'a' }, { projectId: 'p1', projectName: '主项目', periodId: 'b' }, { id: 'not-parent', projectName: '错误ID' }], total: 40 });
  await tick();
  assert.equal(search.options.value.length, 1); assert.equal(search.options.value[0].value, 'p1');
  assert.equal(search.options.value[0].label, '主项目'); assert.equal(search.hasMore.value, true);
  search.loadMore(); assert.equal(calls.at(-1).pageNo, 2);
  pending.shift().reject(new Error('第二页失败')); await tick();
  assert.equal(search.error.value, '第二页失败');
  search.retry(); assert.equal(calls.at(-1).pageNo, 2);
  pending.shift().resolve({ records: [{ projectId: 'p2', projectName: '另一个' }], total: 40 }); await tick();
  assert.equal(search.hasMore.value, false);
  selected = 'p1';
  search.search('  老词 '); timer();
  const older = pending.shift();
  search.search('  新词 '); timer();
  assert.equal(calls.at(-1).keyword, '新词'); assert.equal(calls.at(-1).pageNo, 1);
  pending.shift().resolve({ records: [{ projectId: 'p3', projectName: '新词结果' }], total: 1 }); await tick();
  older.resolve({ records: [{ projectId: 'bad', projectName: '过期' }], total: 1 }); await tick();
  assert.deepEqual(Array.from(search.options.value, (x) => x.value), ['p1', 'p3']);
  search.search(''); timer(); assert.equal(calls.at(-1).keyword, undefined);
  search.close(); pending.shift().resolve({ records: [{ projectId: 'late' }], total: 1 }); await tick();
  assert.equal(search.options.value.some((x) => x.value === 'late'), false);
  search.reset(); assert.equal(search.options.value.length, 0);
  search.search('cancel'); search.close(); assert.equal(timer, undefined);
  const file = 'src/views/project/index.vue';
  const { descriptor } = vue.parse(fs.readFileSync(file, 'utf8'));
  const compiled = vue.compileScript(descriptor, { id: 'project-search' });
  assert.equal(vue.compileTemplate({ source: descriptor.template.content, filename: file, id: 'project-search', compilerOptions: { bindingMetadata: compiled.bindings } }).errors.length, 0);
  assert.match(descriptor.scriptSetup.content, /useMainProjectSearch\(searchPeriod,/);
  assert.doesNotMatch(descriptor.scriptSetup.content, /getMainProjectList/);
  assert.match(descriptor.template.content, /:filter-option="false"/);
  console.log('PASS parent selector: 20/page, projectId dedup, keyword, paging retry, selected label, stale/closed requests, debounce and SFC');
})().catch((e) => { console.error(e); process.exitCode = 1; });
