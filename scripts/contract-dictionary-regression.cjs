const fs = require('node:fs');
const assert = require('node:assert/strict');
const { parse, compileScript, compileTemplate } = require('@vue/compiler-sfc');
const filename = 'src/views/project/contract/index.vue';
const source = fs.readFileSync(filename, 'utf8');
const { descriptor } = parse(source);
compileScript(descriptor, { id: 'contract-dict' });
assert.deepEqual(compileTemplate({ source: descriptor.template.content, filename, id: 'contract-dict' }).errors, []);
assert.match(source, /const auxiliaryDataPromise = Promise.all\(\[loadDictOptions\('contract_type'\), loadDictOptions\('payback_node'\)\]\)/);
assert.match(source, /record.paymentNode_dictText \|\| record.node_dictText \|\| getOptionLabel\(paybackNodeOptions, record.node\)/);
const body = source.match(/function getOptionLabel\([^]*?\) \{([^]*?)\n  \}/)[1];
const label = new Function('options', 'value', body);
const options = [{ value: '1', label: '预付款' }];
assert.equal(label(options, 1), '预付款');
assert.equal(label(options, '1'), '预付款');
assert.equal(label(options, null), '—');
assert.equal(label(options, 'unknown'), 'unknown');
assert.equal(label([], '1'), '1');
console.log('Contract readonly dictionary loading, labels and fallback regression passed');
