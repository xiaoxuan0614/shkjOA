const fs = require('fs'), vm = require('vm'), assert = require('node:assert/strict'), ts = require('typescript');
const exportsObject = {};
vm.runInNewContext(ts.transpileModule(fs.readFileSync('src/views/workflow/repairApplicationSummary.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText, { exports: exportsObject });
const summarize = exportsObject.repairApplicationDepartments;
const departments = [{ departmentId: 'private-id', departmentName: '技术部', reason: '排障\n检查接线', approverIds: ['private-user'] }, { departmentName: '运维部', reason: '现场支持' }];
assert.equal(summarize({ departments })[0].reason, '排障\n检查接线');
assert.equal(summarize({ 'application.formData': { departments } })[1].name, '运维部');
assert.equal(summarize({}).length, 0, 'no visible projection means no data');
assert.equal(summarize({ departments: [] }).length, 0);
assert.equal(summarize({ departments: [null] })[0].name, '部门名称未返回');
assert.ok(!JSON.stringify(summarize({ departments })).includes('private-'));
const drawer = fs.readFileSync('src/views/workflow/components/InstanceDrawer.vue', 'utf8');
assert.ok(drawer.includes('repairApplicationDepartments(visibleSnapshot.value)'));
assert.ok(drawer.includes("detail.value?.processKey === 'repair_ops_collaboration'"));
assert.ok(drawer.includes('key="application" tab="申请内容"'));
assert.ok(drawer.includes('key="progress" tab="审批进程"'));
assert.ok(drawer.includes('<ApprovalProgress :instance="detail" compact />'));
assert.ok(drawer.includes("task.canHandle && task.kind !== 'WORK'"));
assert.ok(drawer.includes("tasks.length === 1 ? tasks[0].id : undefined"), 'multiple tasks require explicit selection');
assert.ok(drawer.includes("chooseAction(selectedApprovalTask!.id, action)"), 'footer submits selected task identity');
console.log('PASS repair application summary');
