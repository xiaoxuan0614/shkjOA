const fs = require('node:fs'), assert = require('node:assert/strict'), ts = require('typescript');
const { parse, compileScript, compileTemplate } = require('@vue/compiler-sfc');
const filename = 'src/views/plan/material-draft/index.vue';
const source = fs.readFileSync(filename, 'utf8');
const schema = fs.readFileSync('src/views/plan/Plan.data.ts', 'utf8');
const { descriptor } = parse(source);
compileScript(descriptor, { id: 'yes-no' });
assert.deepEqual(compileTemplate({ source: descriptor.template.content, filename, id: 'yes-no' }).errors, []);
assert.match(source, /column.dataIndex === 'adopted' \|\| column.dataIndex === 'priced'/);
assert.match(source, /dictText\(record\[column.dataIndex\], 'yesNo'\)/);
assert.match(source, /<a-tag :color="yesNoColor\(record\[column.dataIndex\]\)"/);
const colorFn = source.match(/function yesNoColor\([^]*?\n  \}/)[0];
const color = new Function('yesNoColors', ts.transpile(colorFn) + ';return yesNoColor;')({ value: { '0': '#999999' } });
assert.equal(color(0), '#999999');
assert.equal(color('1'), 'success');
assert.equal(color(null), 'default');
assert.doesNotMatch(source, /isQuotationAdopted|已采用|未采用|已定价|未定价/);
assert.match(schema, /loadQuotationYesNoOptions = \(\) => loadDictOptions\('yes_no_status'\)/);
assert.match(schema, /field: 'adopted',\s*component: 'ApiSelect',\s*componentProps: \{[^}]*api: loadQuotationYesNoOptions/);
const fn = source.match(/function dictText\([^]*?\n  \}/)[0];
const display = new Function('dictionaries', ts.transpile(fn) + ';return dictText;')({ value: { yesNo: { '0': '否', '1': '是' } } });
assert.equal(display(0, 'yesNo'), '否');
assert.equal(display('1', 'yesNo'), '是');
assert.equal(display(null, 'yesNo'), '—');
assert.equal(display('unknown', 'yesNo'), 'unknown');
console.log('PASS quotation adopted/priced dictionary, filter, zero/null/unknown and SFC');
